const std = @import("std");
const Allocator = std.mem.Allocator;
const manifest_mod = @import("../core/manifest.zig");

const AppManifest = manifest_mod.AppManifest;
const FunctionSpec = manifest_mod.FunctionSpec;
const SchemaType = manifest_mod.SchemaType;
const TableSpec = manifest_mod.TableSpec;

/// Zero-dependency codegen emitting browser-native ESM (`api.js`) + full TypeScript declarations
/// (`api.d.ts`, `dataModel.d.ts`) directly from `--introspect` JSON IR.
pub const GeneratedFiles = struct {
    data_model_dts: []u8,
    api_dts: []u8,
    api_js: []u8,

    pub fn deinit(self: *GeneratedFiles, allocator: Allocator) void {
        allocator.free(self.data_model_dts);
        allocator.free(self.api_dts);
        allocator.free(self.api_js);
    }
};

pub fn generateAll(allocator: Allocator, manifest: *const AppManifest) !GeneratedFiles {
    const dm = try generateDataModelDts(allocator, manifest);
    errdefer allocator.free(dm);
    const adts = try generateApiDts(allocator, manifest);
    errdefer allocator.free(adts);
    const ajs = try generateApiJs(allocator, manifest);
    return .{
        .data_model_dts = dm,
        .api_dts = adts,
        .api_js = ajs,
    };
}

pub fn writeGeneratedFiles(allocator: Allocator, io: std.Io, manifest: *const AppManifest, out_dir: []const u8) !void {
    try std.Io.Dir.cwd().createDirPath(io, out_dir);
    var files = try generateAll(allocator, manifest);
    defer files.deinit(allocator);

    const p_dm = try std.fs.path.join(allocator, &.{ out_dir, "dataModel.d.ts" });
    defer allocator.free(p_dm);
    const p_adts = try std.fs.path.join(allocator, &.{ out_dir, "api.d.ts" });
    defer allocator.free(p_adts);
    const p_ajs = try std.fs.path.join(allocator, &.{ out_dir, "api.js" });
    defer allocator.free(p_ajs);

    try std.Io.Dir.cwd().writeFile(io, .{ .sub_path = p_dm, .data = files.data_model_dts });
    try std.Io.Dir.cwd().writeFile(io, .{ .sub_path = p_adts, .data = files.api_dts });
    try std.Io.Dir.cwd().writeFile(io, .{ .sub_path = p_ajs, .data = files.api_js });
}

pub fn generateDataModelDts(allocator: Allocator, manifest: *const AppManifest) ![]u8 {
    var out: std.Io.Writer.Allocating = .init(allocator);
    errdefer out.deinit();
    const w = &out.writer;

    try w.writeAll("// Generated by `concave codegen`. Do not edit manually.\n\n");
    try w.writeAll("export type Id<TableName extends string> = string & { readonly __tableName: TableName };\n\n");

    const TableEntry = struct { ns: []const u8, spec: *const TableSpec };
    var all_tables: std.ArrayList(TableEntry) = .empty;
    defer all_tables.deinit(allocator);

    for (manifest.tables) |*t| try all_tables.append(allocator, .{ .ns = "", .spec = t });
    for (manifest.components) |*c| {
        for (c.tables) |*t| try all_tables.append(allocator, .{ .ns = c.namespace, .spec = t });
    }

    for (all_tables.items) |entry| {
        const qual = try qualifiedTableKey(allocator, entry.ns, entry.spec.name);
        defer allocator.free(qual);
        const type_name = try tableDocTypeName(allocator, entry.ns, entry.spec.name);
        defer allocator.free(type_name);

        try w.print("export interface {s} {{\n", .{type_name});
        try w.print("  id: Id<\"{s}\">;\n", .{qual});
        try w.writeAll("  created_at: number;\n");

        switch (entry.spec.document_schema) {
            .record_t => |fields| {
                for (fields) |f| {
                    if (std.mem.eql(u8, f.name, "id") or
                        std.mem.eql(u8, f.name, "created_at") or
                        std.mem.eql(u8, f.name, "_id") or
                        std.mem.eql(u8, f.name, "_creationTime")) continue;
                    const opt: []const u8 = if (f.optional) "?" else "";
                    try w.print("  {s}{s}: ", .{ f.name, opt });
                    try writeSchemaTs(w, allocator, f.schema);
                    try w.writeAll(";\n");
                }
            },
            else => {
                try w.writeAll("  value: ");
                try writeSchemaTs(w, allocator, entry.spec.document_schema);
                try w.writeAll(";\n");
            },
        }
        try w.writeAll("}\n\n");
    }

    if (all_tables.items.len == 0) {
        try w.writeAll("export type TableNames = never;\n\nexport interface DataModel {}\n");
    } else {
        try w.writeAll("export type TableNames = ");
        for (all_tables.items, 0..) |entry, i| {
            if (i > 0) try w.writeAll(" | ");
            const qual = try qualifiedTableKey(allocator, entry.ns, entry.spec.name);
            defer allocator.free(qual);
            try w.print("\"{s}\"", .{qual});
        }
        try w.writeAll(";\n\nexport interface DataModel {\n");
        for (all_tables.items) |entry| {
            const qual = try qualifiedTableKey(allocator, entry.ns, entry.spec.name);
            defer allocator.free(qual);
            const type_name = try tableDocTypeName(allocator, entry.ns, entry.spec.name);
            defer allocator.free(type_name);
            try w.print("  \"{s}\": {s};\n", .{ qual, type_name });
        }
        try w.writeAll("}\n");
    }

    return try out.toOwnedSlice();
}

const ApiNode = struct {
    children: std.StringArrayHashMapUnmanaged(*ApiNode) = .empty,
    leaf: ?*const FunctionSpec = null,

    fn insert(self: *ApiNode, arena: Allocator, name: []const u8, func: *const FunctionSpec) !void {
        var cur = self;
        var it = std.mem.splitScalar(u8, name, '.');
        while (it.next()) |seg| {
            if (cur.children.get(seg)) |existing| {
                cur = existing;
            } else {
                const child = try arena.create(ApiNode);
                child.* = .{};
                try cur.children.put(arena, seg, child);
                cur = child;
            }
        }
        cur.leaf = func;
    }

    fn renderDts(self: *const ApiNode, w: *std.Io.Writer, allocator: Allocator, indent: usize) !void {
        if (self.leaf) |func| {
            try w.print("FunctionReference<\"{s}\", ", .{func.kind.toStr()});
            try writeSchemaTs(w, allocator, func.args_schema);
            try w.writeAll(", ");
            try writeSchemaTs(w, allocator, func.returns_schema);
            try w.writeByte('>');
            return;
        }
        try w.writeAll("{\n");
        var it = self.children.iterator();
        while (it.next()) |entry| {
            try writeIndent(w, indent + 1);
            try w.print("readonly {s}: ", .{entry.key_ptr.*});
            try entry.value_ptr.*.renderDts(w, allocator, indent + 1);
            try w.writeAll(";\n");
        }
        try writeIndent(w, indent);
        try w.writeByte('}');
    }

    fn renderJs(self: *const ApiNode, w: *std.Io.Writer, indent: usize) !void {
        if (self.leaf) |func| {
            try w.print("makeRef(\"{s}\", \"{s}\")", .{ func.kind.toStr(), func.name });
            return;
        }
        try w.writeAll("{\n");
        var it = self.children.iterator();
        while (it.next()) |entry| {
            try writeIndent(w, indent + 1);
            try w.print("{s}: ", .{entry.key_ptr.*});
            if (entry.value_ptr.*.leaf != null) {
                try entry.value_ptr.*.renderJs(w, indent + 1);
            } else {
                try w.writeAll("Object.freeze(");
                try entry.value_ptr.*.renderJs(w, indent + 1);
                try w.writeByte(')');
            }
            try w.writeAll(",\n");
        }
        try writeIndent(w, indent);
        try w.writeByte('}');
    }
};

pub fn generateApiDts(allocator: Allocator, manifest: *const AppManifest) ![]u8 {
    var arena = std.heap.ArenaAllocator.init(allocator);
    defer arena.deinit();
    var root: ApiNode = .{};
    for (manifest.functions) |*f| {
        try root.insert(arena.allocator(), f.name, f);
    }

    var out: std.Io.Writer.Allocating = .init(allocator);
    errdefer out.deinit();
    const w = &out.writer;

    try w.writeAll(
        \\// Generated by `concave codegen`. Do not edit manually.
        \\import type { Id } from "./dataModel.d.ts";
        \\
        \\export type FunctionKind = "query" | "mutation" | "action";
        \\
        \\export interface FunctionReference<
        \\  Kind extends FunctionKind,
        \\  Args,
        \\  Result
        \\> {
        \\  readonly kind: Kind;
        \\  readonly name: string;
        \\  readonly __args?: Args;
        \\  readonly __result?: Result;
        \\}
        \\
        \\export declare const api: 
    );
    try root.renderDts(w, allocator, 0);
    try w.writeAll(
        \\;
        \\
        \\export type Api = typeof api;
        \\
        \\export type FunctionReferenceLike<
        \\  Kind extends FunctionKind,
        \\  Args,
        \\  Result
        \\> =
        \\  | FunctionReference<Kind, Args, Result>
        \\  | { readonly ref: FunctionReference<Kind, Args, Result> };
        \\
        \\export interface QueryState<T> {
        \\  readonly status: "paused" | "loading" | "ready" | "error";
        \\  readonly data: T | undefined;
        \\  readonly error: string | undefined;
        \\}
        \\
        \\export interface OptimisticLocalStore {
        \\  getQuery<Args, Result>(
        \\    ref: FunctionReferenceLike<"query", Args, Result>,
        \\    args: Args,
        \\  ): Result | undefined;
        \\  setQuery<Args, Result>(
        \\    ref: FunctionReferenceLike<"query", Args, Result>,
        \\    args: Args,
        \\    value: Result,
        \\  ): void;
        \\}
        \\
        \\export interface MutateOptions {
        \\  optimisticUpdate?: (store: OptimisticLocalStore) => void;
        \\}
        \\
        \\export interface BoundQuery<Args, Result> {
        \\  (
        \\    ...args: Record<string, never> extends Args
        \\      ? [argsOrAccessor?: Args | (() => Args | null | undefined)]
        \\      : [argsOrAccessor: Args | (() => Args | null | undefined)]
        \\  ): (() => QueryState<Result>) & { dispose: () => void };
        \\  once(
        \\    ...args: Record<string, never> extends Args ? [args?: Args] : [args: Args]
        \\  ): Promise<Result>;
        \\  readonly ref: FunctionReference<"query", Args, Result>;
        \\}
        \\
        \\export interface BoundMutation<Args, Result> {
        \\  (
        \\    ...args: Record<string, never> extends Args
        \\      ? [args?: Args, options?: MutateOptions]
        \\      : [args: Args, options?: MutateOptions]
        \\  ): Promise<Result>;
        \\  readonly ref: FunctionReference<"mutation", Args, Result>;
        \\}
        \\
        \\export interface BoundAction<Args, Result> {
        \\  (
        \\    ...args: Record<string, never> extends Args ? [args?: Args] : [args: Args]
        \\  ): Promise<Result>;
        \\  readonly ref: FunctionReference<"action", Args, Result>;
        \\}
        \\
        \\export interface ConcaveClientLike {
        \\  query<Args, Result>(
        \\    ref: FunctionReferenceLike<"query", Args, Result>,
        \\    argsOrAccessor: Args | (() => Args | null | undefined),
        \\  ): (() => QueryState<Result>) & { dispose: () => void };
        \\  mutate<Args, Result>(
        \\    ref: FunctionReferenceLike<"mutation", Args, Result>,
        \\    args: Args,
        \\    options?: MutateOptions,
        \\  ): Promise<Result>;
        \\  action<Args, Result>(
        \\    ref: FunctionReferenceLike<"action", Args, Result>,
        \\    args: Args,
        \\  ): Promise<Result>;
        \\  queryOnce<Args, Result>(
        \\    ref: FunctionReferenceLike<"query", Args, Result>,
        \\    args: Args,
        \\  ): Promise<Result>;
        \\}
        \\
        \\export type BoundApi<T> = {
        \\  readonly [K in keyof T]: T[K] extends FunctionReference<"query", infer A, infer R>
        \\    ? BoundQuery<A, R>
        \\    : T[K] extends FunctionReference<"mutation", infer A, infer R>
        \\      ? BoundMutation<A, R>
        \\      : T[K] extends FunctionReference<"action", infer A, infer R>
        \\        ? BoundAction<A, R>
        \\        : BoundApi<T[K]>;
        \\};
        \\
        \\export declare function createApi(client: ConcaveClientLike): BoundApi<Api>;
        \\
    );
    return try out.toOwnedSlice();
}

pub fn generateApiJs(allocator: Allocator, manifest: *const AppManifest) ![]u8 {
    var arena = std.heap.ArenaAllocator.init(allocator);
    defer arena.deinit();
    var root: ApiNode = .{};
    for (manifest.functions) |*f| {
        try root.insert(arena.allocator(), f.name, f);
    }

    var out: std.Io.Writer.Allocating = .init(allocator);
    errdefer out.deinit();
    const w = &out.writer;

    try w.writeAll(
        \\// Generated by `concave codegen`. Do not edit manually.
        \\
        \\function makeRef(kind, name) {
        \\  return Object.freeze({ kind, name });
        \\}
        \\
        \\export const api = Object.freeze(
    );
    try root.renderJs(w, 0);
    try w.writeAll(
        \\);
        \\
        \\function bindNode(node, client) {
        \\  if (node && typeof node.kind === "string" && typeof node.name === "string") {
        \\    const fn =
        \\      node.kind === "query"
        \\        ? (args = {}) => client.query(node, args)
        \\        : node.kind === "mutation"
        \\          ? (args = {}, options) => client.mutate(node, args, options)
        \\          : (args = {}) => client.action(node, args);
        \\    fn.ref = node;
        \\    if (node.kind === "query") {
        \\      fn.once = (args = {}) => client.queryOnce(node, args);
        \\    }
        \\    return fn;
        \\  }
        \\  const out = {};
        \\  for (const key of Object.keys(node)) {
        \\    out[key] = bindNode(node[key], client);
        \\  }
        \\  return Object.freeze(out);
        \\}
        \\
        \\export function createApi(client) {
        \\  return bindNode(api, client);
        \\}
        \\
    );
    return try out.toOwnedSlice();
}

fn writeSchemaTs(w: *std.Io.Writer, allocator: Allocator, schema: SchemaType) !void {
    switch (schema) {
        .null_t => try w.writeAll("null"),
        .bool_t => try w.writeAll("boolean"),
        .int_t, .float_t => try w.writeAll("number"),
        .str_t => try w.writeAll("string"),
        .any_t => try w.writeAll("unknown"),
        .id_t => |id_s| {
            const qual = try qualifiedTableKey(allocator, id_s.namespace, id_s.table);
            defer allocator.free(qual);
            try w.print("Id<\"{s}\">", .{qual});
        },
        .list_t => |item| {
            try w.writeAll("Array<");
            try writeSchemaTs(w, allocator, item.*);
            try w.writeByte('>');
        },
        .optional_t => |inner| {
            try w.writeByte('(');
            try writeSchemaTs(w, allocator, inner.*);
            try w.writeAll(" | null)");
        },
        .record_t => |fields| {
            if (fields.len == 0) {
                try w.writeAll("Record<string, never>");
                return;
            }
            try w.writeAll("{ ");
            for (fields, 0..) |f, i| {
                if (i > 0) try w.writeAll("; ");
                const opt: []const u8 = if (f.optional) "?" else "";
                try w.print("{s}{s}: ", .{ f.name, opt });
                try writeSchemaTs(w, allocator, f.schema);
            }
            try w.writeAll(" }");
        },
        .union_t => |variants| {
            if (variants.len == 0) {
                try w.writeAll("never");
                return;
            }
            try w.writeByte('(');
            for (variants, 0..) |v, i| {
                if (i > 0) try w.writeAll(" | ");
                if (v.payload) |p| {
                    try w.print("{{ tag: \"{s}\"; value: ", .{v.tag});
                    try writeSchemaTs(w, allocator, p.*);
                    try w.writeAll(" }");
                } else {
                    try w.print("{{ tag: \"{s}\" }}", .{v.tag});
                }
            }
            try w.writeByte(')');
        },
    }
}

fn writeIndent(w: *std.Io.Writer, level: usize) !void {
    for (0..level) |_| try w.writeAll("  ");
}

fn qualifiedTableKey(allocator: Allocator, ns: []const u8, table: []const u8) ![]u8 {
    if (ns.len == 0) return try allocator.dupe(u8, table);
    return try std.fmt.allocPrint(allocator, "{s}::{s}", .{ ns, table });
}

fn tableDocTypeName(allocator: Allocator, ns: []const u8, table: []const u8) ![]u8 {
    var out: std.ArrayList(u8) = .empty;
    errdefer out.deinit(allocator);
    if (ns.len > 0) try appendPascalCase(allocator, &out, ns);
    try appendPascalCase(allocator, &out, table);
    try out.appendSlice(allocator, "Doc");
    return try out.toOwnedSlice(allocator);
}

fn appendPascalCase(allocator: Allocator, out: *std.ArrayList(u8), s: []const u8) !void {
    var upper_next = true;
    for (s) |c| {
        if (!std.ascii.isAlphanumeric(c)) {
            upper_next = true;
            continue;
        }
        if (upper_next) {
            try out.append(allocator, std.ascii.toUpper(c));
            upper_next = false;
        } else {
            try out.append(allocator, c);
        }
    }
}

test "codegen emits api.js, api.d.ts, and dataModel.d.ts" {
    const allocator = std.testing.allocator;
    const sample =
        \\{"app_name":"chat","tables":[{"name":"messages","document_schema":{"kind":"record","fields":[{"name":"room_id","schema":{"kind":"id","table":"rooms","namespace":""},"optional":false},{"name":"body","schema":{"kind":"str"},"optional":false}]},"indexes":[]}],"components":[{"namespace":"presence","package":"concave-presence","tables":[{"name":"sessions","document_schema":{"kind":"record","fields":[{"name":"user","schema":{"kind":"str"},"optional":false}]},"indexes":[]}]}],"functions":[{"name":"messages.list","kind":"query","namespace":"","args_schema":{"kind":"record","fields":[{"name":"room_id","schema":{"kind":"id","table":"rooms","namespace":""},"optional":false}]},"returns_schema":{"kind":"list","item":{"kind":"any"}}}]}
    ;
    var manifest = try AppManifest.parseJson(allocator, sample);
    defer manifest.deinit();

    var files = try generateAll(allocator, &manifest);
    defer files.deinit(allocator);

    try std.testing.expect(std.mem.indexOf(u8, files.data_model_dts, "export interface MessagesDoc") != null);
    try std.testing.expect(std.mem.indexOf(u8, files.data_model_dts, "export interface PresenceSessionsDoc") != null);
    try std.testing.expect(std.mem.indexOf(u8, files.api_dts, "FunctionReference<\"query\"") != null);
    try std.testing.expect(std.mem.indexOf(u8, files.api_dts, "export declare function createApi") != null);
    try std.testing.expect(std.mem.indexOf(u8, files.api_js, "makeRef(\"query\", \"messages.list\")") != null);
    try std.testing.expect(std.mem.indexOf(u8, files.api_js, "export function createApi(client)") != null);
}
