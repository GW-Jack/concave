use std::collections::BTreeMap;
use std::fs;
use std::path::Path;

use concave_core::{AppManifest, FunctionKind, FunctionSpec, SchemaType, TableSpec};

/// Generated TypeScript files emitted by `concave codegen`.
/// Concave's Rust server transpiles `.ts` files to browser ESM on the fly via `oxc` (zero npm/bundler).
#[derive(Debug, Clone)]
pub struct GeneratedFiles {
    pub data_model_ts: String,
    pub api_ts: String,
}

pub fn generate_typescript(manifest: &AppManifest) -> GeneratedFiles {
    GeneratedFiles {
        data_model_ts: generate_data_model_ts(manifest),
        api_ts: generate_api_ts(manifest),
    }
}

pub fn write_generated_files(manifest: &AppManifest, out_dir: &Path) -> std::io::Result<()> {
    fs::create_dir_all(out_dir)?;
    let files = generate_typescript(manifest);
    fs::write(out_dir.join("dataModel.ts"), files.data_model_ts)?;
    fs::write(out_dir.join("api.ts"), files.api_ts)?;
    Ok(())
}

pub fn generate_data_model_ts(manifest: &AppManifest) -> String {
    let mut out = String::new();
    out.push_str("// Generated by `concave codegen`. Do not edit manually.\n\n");
    out.push_str(
        "export type Id<TableName extends string> = string & { readonly __tableName: TableName };\n\n",
    );

    let all_tables = manifest.all_tables();

    for (ns, table) in &all_tables {
        let qualified = qualified_table_key(ns, &table.name);
        let type_name = table_doc_type_name(ns, &table.name);
        out.push_str(&format!("export interface {type_name} {{\n"));
        out.push_str(&format!("  id: Id<\"{}\">;\n", qualified));
        out.push_str("  created_at: number;\n");
        if let SchemaType::Record { fields } = &table.document_schema {
            for field in fields {
                if field.name == "id"
                    || field.name == "created_at"
                    || field.name == "_id"
                    || field.name == "_creationTime"
                {
                    continue;
                }
                let opt = if field.optional { "?" } else { "" };
                out.push_str(&format!(
                    "  {}{}: {};\n",
                    field.name,
                    opt,
                    schema_to_ts(&field.schema)
                ));
            }
        } else {
            out.push_str(&format!(
                "  value: {};\n",
                schema_to_ts(&table.document_schema)
            ));
        }
        out.push_str("}\n\n");
    }

    if all_tables.is_empty() {
        out.push_str("export type TableNames = never;\n\n");
        out.push_str("export interface DataModel {}\n");
    } else {
        let names: Vec<String> = all_tables
            .iter()
            .map(|(ns, t)| format!("\"{}\"", qualified_table_key(ns, &t.name)))
            .collect();
        out.push_str(&format!("export type TableNames = {};\n\n", names.join(" | ")));
        out.push_str("export interface DataModel {\n");
        for (ns, t) in &all_tables {
            let key = qualified_table_key(ns, &t.name);
            let type_name = table_doc_type_name(ns, &t.name);
            out.push_str(&format!("  \"{key}\": {type_name};\n"));
        }
        out.push_str("}\n");
    }

    out
}

pub fn generate_api_ts(manifest: &AppManifest) -> String {
    let mut out = String::new();
    out.push_str("// Generated by `concave codegen`. Do not edit manually.\n");
    out.push_str("import type { Id } from \"./dataModel.ts\";\n\n");
    out.push_str(
        "export type FunctionKind = \"query\" | \"mutation\" | \"action\";\n\n\
         export interface FunctionReference<\n\
           Kind extends FunctionKind,\n\
           Args,\n\
           Result\n\
         > {\n\
           readonly kind: Kind;\n\
           readonly name: string;\n\
           readonly __args?: Args;\n\
           readonly __result?: Result;\n\
         }\n\n\
         function makeRef<Kind extends FunctionKind, Args, Result>(\n\
           kind: Kind,\n\
           name: string\n\
         ): FunctionReference<Kind, Args, Result> {\n\
           return { kind, name };\n\
         }\n\n",
    );

    let mut root = ApiNode::default();
    for func in &manifest.functions {
        let segments: Vec<&str> = func.name.split('.').collect();
        root.insert(&segments, func);
    }

    out.push_str("export const api = ");
    root.render(&mut out, 0);
    out.push_str(" as const;\n\n");
    out.push_str("export type Api = typeof api;\n");
    out
}

#[derive(Default)]
struct ApiNode<'a> {
    children: BTreeMap<String, ApiNode<'a>>,
    leaf: Option<&'a FunctionSpec>,
}

impl<'a> ApiNode<'a> {
    fn insert(&mut self, segments: &[&str], func: &'a FunctionSpec) {
        if let Some((first, rest)) = segments.split_first() {
            let child = self.children.entry((*first).to_string()).or_default();
            if rest.is_empty() {
                child.leaf = Some(func);
            } else {
                child.insert(rest, func);
            }
        }
    }

    fn render(&self, out: &mut String, indent: usize) {
        if let Some(func) = self.leaf {
            let kind_str = match func.kind {
                FunctionKind::Query => "query",
                FunctionKind::Mutation => "mutation",
                FunctionKind::Action => "action",
            };
            let args_ts = schema_to_ts(&func.args_schema);
            let ret_ts = schema_to_ts(&func.returns_schema);
            out.push_str(&format!(
                "makeRef<\"{kind_str}\", {args_ts}, {ret_ts}>(\"{kind_str}\", \"{}\")",
                func.name
            ));
            return;
        }

        out.push_str("{\n");
        let pad = "  ".repeat(indent + 1);
        for (key, child) in &self.children {
            out.push_str(&format!("{pad}{key}: "));
            child.render(out, indent + 1);
            out.push_str(",\n");
        }
        out.push_str(&format!("{}}}", "  ".repeat(indent)));
    }
}

pub fn schema_to_ts(schema: &SchemaType) -> String {
    match schema {
        SchemaType::Null => "null".into(),
        SchemaType::Bool => "boolean".into(),
        SchemaType::Int | SchemaType::Float => "number".into(),
        SchemaType::Str => "string".into(),
        SchemaType::Id { table, namespace } => {
            let qualified = qualified_table_key(namespace, table);
            format!("Id<\"{qualified}\">")
        }
        SchemaType::List { item } => format!("Array<{}>", schema_to_ts(item)),
        SchemaType::Optional { inner } => format!("({} | null)", schema_to_ts(inner)),
        SchemaType::Record { fields } => {
            if fields.is_empty() {
                return "Record<string, never>".into();
            }
            let parts: Vec<String> = fields
                .iter()
                .map(|f| {
                    let opt = if f.optional { "?" } else { "" };
                    format!("{}{}: {}", f.name, opt, schema_to_ts(&f.schema))
                })
                .collect();
            format!("{{ {} }}", parts.join("; "))
        }
        SchemaType::Union { variants } => {
            if variants.is_empty() {
                return "never".into();
            }
            let parts: Vec<String> = variants
                .iter()
                .map(|v| match &v.payload {
                    Some(p) => format!("{{ tag: \"{}\"; value: {} }}", v.tag, schema_to_ts(p)),
                    None => format!("{{ tag: \"{}\" }}", v.tag),
                })
                .collect();
            format!("({})", parts.join(" | "))
        }
        SchemaType::Any => "unknown".into(),
    }
}

fn qualified_table_key(namespace: &str, table: &str) -> String {
    if namespace.is_empty() {
        table.to_string()
    } else {
        format!("{namespace}::{table}")
    }
}

fn table_doc_type_name(namespace: &str, table: &str) -> String {
    let mut name = String::new();
    if !namespace.is_empty() {
        name.push_str(&to_pascal_case(namespace));
    }
    name.push_str(&to_pascal_case(table));
    name.push_str("Doc");
    name
}

fn to_pascal_case(s: &str) -> String {
    s.split(|c: char| !c.is_alphanumeric())
        .filter(|part| !part.is_empty())
        .map(|part| {
            let mut chars = part.chars();
            match chars.next() {
                Some(first) => first.to_uppercase().collect::<String>() + chars.as_str(),
                None => String::new(),
            }
        })
        .collect()
}

/// Convenience helper for generating TS types for a single table spec.
pub fn table_schema_ts(table: &TableSpec) -> String {
    schema_to_ts(&table.document_schema)
}

#[cfg(test)]
mod tests {
    use concave_core::{ComponentSpec, FieldSpec, IndexSpec};

    use super::*;

    #[test]
    fn generates_typed_data_model_and_nested_api() {
        let manifest = AppManifest {
            app_name: "chat".into(),
            tables: vec![TableSpec {
                name: "messages".into(),
                document_schema: SchemaType::Record {
                    fields: vec![
                        FieldSpec {
                            name: "room_id".into(),
                            schema: SchemaType::Id {
                                table: "rooms".into(),
                                namespace: "".into(),
                            },
                            optional: false,
                        },
                        FieldSpec {
                            name: "body".into(),
                            schema: SchemaType::Str,
                            optional: false,
                        },
                    ],
                },
                indexes: vec![IndexSpec {
                    name: "by_room".into(),
                    fields: vec!["room_id".into()],
                }],
            }],
            components: vec![ComponentSpec {
                namespace: "presence".into(),
                package: "concave-presence".into(),
                tables: vec![TableSpec {
                    name: "sessions".into(),
                    document_schema: SchemaType::Record {
                        fields: vec![FieldSpec {
                            name: "user".into(),
                            schema: SchemaType::Str,
                            optional: false,
                        }],
                    },
                    indexes: vec![],
                }],
            }],
            functions: vec![
                FunctionSpec {
                    name: "messages.list".into(),
                    kind: FunctionKind::Query,
                    namespace: "".into(),
                    args_schema: SchemaType::Record {
                        fields: vec![FieldSpec {
                            name: "room_id".into(),
                            schema: SchemaType::Id {
                                table: "rooms".into(),
                                namespace: "".into(),
                            },
                            optional: false,
                        }],
                    },
                    returns_schema: SchemaType::List {
                        item: Box::new(SchemaType::Any),
                    },
                },
                FunctionSpec {
                    name: "presence.heartbeat".into(),
                    kind: FunctionKind::Mutation,
                    namespace: "presence".into(),
                    args_schema: SchemaType::Record {
                        fields: vec![FieldSpec {
                            name: "room".into(),
                            schema: SchemaType::Str,
                            optional: false,
                        }],
                    },
                    returns_schema: SchemaType::Bool,
                },
            ],
        };

        let files = generate_typescript(&manifest);
        assert!(files.data_model_ts.contains("export interface MessagesDoc"));
        assert!(files
            .data_model_ts
            .contains("export interface PresenceSessionsDoc"));
        assert!(files
            .data_model_ts
            .contains("id: Id<\"presence::sessions\">;"));
        assert!(files
            .api_ts
            .contains("makeRef<\"query\", { room_id: Id<\"rooms\"> }, Array<unknown>>(\"query\", \"messages.list\")"));
        assert!(files
            .api_ts
            .contains("makeRef<\"mutation\", { room: string }, boolean>(\"mutation\", \"presence.heartbeat\")"));
    }
}
